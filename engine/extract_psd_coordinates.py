def classify_semantic_family(layer_name: str) -> str | None:
    """Classify a PSD layer into a semantic duplicate family via regex."""
    for family, pattern in SEMANTIC_FAMILY_PATTERNS:
        if pattern.search(layer_name):
            return family
    return None


def parse_layer_key_and_copy(layer_name: str):
    """Extract canonical base key and optional copy suffix (e.g. 'copy', 'copy 2')."""
    copy_match = re.search(r"\bcopy(?:\s+(\d+))?$", layer_name.strip(), flags=re.IGNORECASE)
    copy_suffix = None
    if copy_match:
        num = copy_match.group(1)
        copy_suffix = f"copy_{num}" if num else "copy"

    # Match against known prefixes
    for key in LAYER_MAPPING:
        if layer_name.startswith(key):
            return key, copy_suffix
    # Fallback via semantic family regex for arbitrary user-renamed duplicates
    family = classify_semantic_family(layer_name)
    if family == "tangerine":
        return ("Flying_Single_Tangerine" if "flying" in layer_name.lower() else "Tucked_Tangerine_Cluster"), copy_suffix
    if family == "tissue":
        return "Tucked_Toilet_Paper", copy_suffix
    if family == "snowflake":
        return "Decor_Snowflake", copy_suffix
    return layer_name.split(" ")[0], copy_suffix


def estimate_rotation_deg(layer_img: Image.Image, asset_path: Path, flip_x: bool = False) -> float:
    """
    Estimate CSS clockwise rotation (degrees in [-180, 180)) of a raster PSD layer
    relative to its original asset PNG by maximizing alpha+luma correlation across angles.
    """
    if not asset_path or not asset_path.exists():
        return 0.0

    src = Image.open(asset_path).convert("RGBA")
    if flip_x:
        src = src.transpose(Image.FLIP_LEFT_RIGHT)
    # Tight-crop source alpha
    src_bbox = src.getbbox()
    if src_bbox:
        src = src.crop(src_bbox)

    # Tight-crop target layer alpha (threshold > 30 to ignore faint drop-shadow halo)
    tgt_rgba = layer_img.convert("RGBA")
    tgt_arr = np.array(tgt_rgba)
    mask = tgt_arr[:, :, 3] > 60
    if not mask.any():
        return 0.0
    ys, xs = np.where(mask)
    tgt_crop = tgt_rgba.crop((int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1))

    # Normalize target to 64x64 grayscale*alpha
    S = 64
    tgt_small = tgt_crop.resize((S, S), Image.Resampling.BILINEAR)
    ta = np.array(tgt_small, dtype=np.float32)
    t_feat = (0.299 * ta[:, :, 0] + 0.587 * ta[:, :, 1] + 0.114 * ta[:, :, 2] + 64.0) * (ta[:, :, 3] / 255.0)
    t_norm = np.linalg.norm(t_feat) + 1e-6
    t_feat /= t_norm

    # Downscale src once for fast coarse search
    src_small = src.copy()
    src_small.thumbnail((96, 96), Image.Resampling.BILINEAR)

    def score_angle(css_deg: float) -> float:
        # PIL rotate is CCW, CSS rotate is CW -> pass -css_deg
        rot = src_small.rotate(-css_deg, resample=Image.Resampling.BILINEAR, expand=True)
        rb = rot.getbbox()
        if not rb:
            return -1.0
        rot = rot.crop(rb).resize((S, S), Image.Resampling.BILINEAR)
        ra = np.array(rot, dtype=np.float32)
        r_feat = (0.299 * ra[:, :, 0] + 0.587 * ra[:, :, 1] + 0.114 * ra[:, :, 2] + 64.0) * (ra[:, :, 3] / 255.0)
        r_norm = np.linalg.norm(r_feat) + 1e-6
        return float(np.sum(t_feat * (r_feat / r_norm)))

    # Coarse search every 4 degrees in [-90, 90] (plus full check if needed)
    best_deg = 0.0
    best_score = -1.0
    for deg in range(-90, 92, 4):
        sc = score_angle(float(deg))
        if sc > best_score:
            best_score = sc
            best_deg = float(deg)

    # Fine search +/- 4 degrees at 1-degree steps
    fine_best_deg = best_deg
    fine_best_score = best_score
    for deg in range(int(best_deg) - 4, int(best_deg) + 5):
        sc = score_angle(float(deg))
        if sc > fine_best_score:
            fine_best_score = sc
            fine_best_deg = float(deg)

    return round(fine_best_deg, 1)


def main():
    if not SOURCE_PSD.exists():
        raise FileNotFoundError(f"Source PSD not found: {SOURCE_PSD}")

    psd = PSDImage.open(str(SOURCE_PSD))
    extracted = []
    z_order = 0
    family_counts: dict[str, int] = {}
    base_key_counts: dict[str, int] = {}

    def walk(container, group_path=""):
        nonlocal z_order
        for layer in container:
            if layer.is_group():
                next_group = f"{group_path}/{layer.name}" if group_path else layer.name
                walk(layer, next_group)
                continue

            z_order += 1
            base_key, copy_suffix = parse_layer_key_and_copy(layer.name)
            base_key_counts[base_key] = base_key_counts.get(base_key, 0) + 1
            occurrence_idx = base_key_counts[base_key]
            is_duplicate = bool(copy_suffix) or occurrence_idx > 1
            if is_duplicate and not copy_suffix:
                copy_suffix = "copy" if occurrence_idx == 2 else f"copy_{occurrence_idx - 1}"

            semantic_family = classify_semantic_family(layer.name)
            family_index = None
            family_instance_id = None
            if semantic_family:
                family_counts[semantic_family] = family_counts.get(semantic_family, 0) + 1
                family_index = family_counts[semantic_family]
                family_instance_id = f"{semantic_family}_{family_index}"

            mapping = LAYER_MAPPING.get(base_key, {})
            baseline = BASELINE_PSD_BBOXES.get(base_key)
            z_index = LAYER_Z_INDEX.get(base_key, z_order)

            element_id = mapping.get("element_id", f"#{base_key.lower()}")
            css_selector = mapping.get("css_selector", f".{base_key.lower()}")
            if copy_suffix:
                element_id = f"{element_id}_{copy_suffix}"
                css_selector = f"{css_selector}-{copy_suffix.replace('_', '-')}"

            left = int(layer.left)
            top = int(layer.top)
            width = int(layer.width)
            height = int(layer.height)
            cx = round(left + width / 2.0, 1)
            cy = round(top + height / 2.0, 1)

            delta_x = left - baseline["left"] if baseline else 0
            delta_y = top - baseline["top"] if baseline else 0
            scale_x = round(width / baseline["width"], 4) if baseline and baseline["width"] else 1.0
            scale_y = round(height / baseline["height"], 4) if baseline and baseline["height"] else 1.0
            moved_or_resized = bool(
                copy_suffix
                or abs(delta_x) > 0
                or abs(delta_y) > 0
                or abs(scale_x - 1.0) > 0.01
                or abs(scale_y - 1.0) > 0.01
            )

            # Estimate rotation for movable product/decor items if changed or duplicated
            estimated_rot = mapping.get("baseline_rot_deg", 0.0)
            rotatable_keys = {
                "Tucked_Toilet_Paper",
                "Tucked_Tangerine_Cluster",
                "Shopping_Bag_Pink",
                "Burst_Knit_Sweater",
                "Burst_Puffer_Jacket",
                "Decor_Bauble",
                "Decor_Candy_Cane",
                "Decor_Snowflake",
                "Flying_Single_Tangerine",
                "Decor_Flying_Lid",
            }
            if base_key in rotatable_keys and moved_or_resized and mapping.get("asset"):
                try:
                    l_img = layer.topil()
                    if l_img is not None:
                        estimated_rot = estimate_rotation_deg(
                            l_img,
                            ROOT_DIR / mapping["asset"],
                            flip_x=mapping.get("flip_x", False),
                        )
                except Exception as exc:
                    print(f"[WARN] Rotation estimation failed for {layer.name}: {exc}")

            entry = {
                "z_order": z_order,
                "z_index": z_index,
                "group": group_path,
                "psd_layer_name": layer.name,
                "base_key": base_key,
                "semantic_family": semantic_family,
                "family_index": family_index,
                "family_instance_id": family_instance_id,
                "is_duplicate": is_duplicate,
                "copy_suffix": copy_suffix,
                "element_id": element_id,
                "css_selector": css_selector,
                "asset": mapping.get("asset"),
                "visible": bool(layer.visible),
                "opacity": int(layer.opacity),
                "bbox": {
                    "left": left,
                    "top": top,
                    "width": width,
                    "height": height,
                    "right": left + width,
                    "bottom": top + height,
                    "center_x": cx,
                    "center_y": cy,
                },
                "baseline_bbox": baseline,
                "delta": {
                    "dx": delta_x,
                    "dy": delta_y,
                    "scale_x": scale_x,
                    "scale_y": scale_y,
                    "changed": moved_or_resized,
                },
                "rotation": {
                    "baseline_deg": mapping.get("baseline_rot_deg", 0.0),
                    "estimated_deg": estimated_rot,
                },
            }
            extracted.append(entry)

    walk(psd)

    duplicate_layers = [e for e in extracted if e["is_duplicate"]]
    payload = {
        "directive_id": "DIR-EXTRACT-DUPLICATES-PRESERVE-FX-040",
        "source_psd": str(SOURCE_PSD),
        "canvas": {"width": psd.width, "height": psd.height},
        "layer_count": len(extracted),
        "duplicate_count": len(duplicate_layers),
        "family_counts": family_counts,
        "layers": extracted,
    }

    OUTPUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_JSON.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"[EXTRACT] Wrote {OUTPUT_JSON} ({len(extracted)} layers, {len(duplicate_layers)} duplicates)")
    print(f"[EXTRACT] Semantic Families: {json.dumps(family_counts, ensure_ascii=False)}")
    print("-" * 140)
    print(f"{'Z':>2} | {'ZIdx':>4} | {'Family ID':<14} | {'Element ID':<28} | {'Left':>5} {'Top':>5} {'W':>5} {'H':>5} | {'dX':>5} {'dY':>5} {'sX':>6} {'sY':>6} | {'Rot(old->new)':<14} | {'Flag'}")
    print("-" * 140)
    for e in extracted:
        b = e["bbox"]
        d = e["delta"]
        r = e["rotation"]
        rot_str = f"{r['baseline_deg']:+.0f} -> {r['estimated_deg']:+.0f}"
        fam_str = e["family_instance_id"] or "-"
        flag = "DUP" if e["is_duplicate"] else ("YES" if d["changed"] else "no")
        print(
            f"{e['z_order']:>2} | {e['z_index']:>4} | {fam_str:<14} | {e['element_id']:<28} | "
            f"{b['left']:>5} {b['top']:>5} {b['width']:>5} {b['height']:>5} | "
            f"{d['dx']:>+5} {d['dy']:>+5} {d['scale_x']:>6.2f} {d['scale_y']:>6.2f} | "
            f"{rot_str:<14} | {flag}"
        )


if __name__ == "__main__":
    main()